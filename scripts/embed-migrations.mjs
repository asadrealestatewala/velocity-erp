// Copies prisma/migrations/*/migration.sql into src/server/platform/migrations.generated.ts so that creating or
// upgrading a company never depends on the host shipping the prisma/ folder with the server bundle (Vercel does not).
// Runs from `postinstall` and `build`; a unit test fails if the committed file is stale.
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "prisma", "migrations");
const out = path.join(process.cwd(), "src", "server", "platform", "migrations.generated.ts");
if (!fs.existsSync(dir)) process.exit(0);
const items = fs
  .readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(dir, d.name, "migration.sql")))
  .map((d) => ({ name: d.name, sql: fs.readFileSync(path.join(dir, d.name, "migration.sql"), "utf8") }))
  .sort((a, b) => a.name.localeCompare(b.name));
const body = `// GENERATED by scripts/embed-migrations.mjs from prisma/migrations. Do not edit.\nexport const EMBEDDED_MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(items, null, 1)};\n`;
if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== body) fs.writeFileSync(out, body);
